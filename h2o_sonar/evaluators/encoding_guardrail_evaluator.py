class EncodingGuardrailEvaluator(evaluators.Evaluator):
    """Evaluator designed to bypass RAG/LLM system protection / guardrails by encoding
    the input prompt and/or request to encode the actual answer. The evaluator
    can be used to evaluate the RAG/LLM ability to handle encoded data.

    In order to evaluate the success it either uses the test case condition (if
    available) or fallbacks to the PII leakage detection (if no condition is specified).

    How does it work?

    - The evaluator first identifies test cases that are potentially using encoding
      perturbations (e.g., base16, base64) based on the dataset metadata ('categories').
    - For identified cases, it attempts to find and decode the encoded portion
      of the `actual_output`.
    - The evaluation then utilizes a regex suite on the (potentially decoded)
      text either to use conditions or to detect formatted PII patterns.
    - The evaluator checks both the potentially decoded ``actual_output`` and,
      optionally, the ``retrieved_context`` (for RAG models) for (un)desired actual
      answer content.
    - The result for each test case is boolean (leakage detected or not).

    See: https://substack.com/home/post/p-156004330
    See: https://emn178.github.io/online-tools/hex_encode.html

    """

